import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import type { FileCheckContext } from 'declapract';
import { given, then, useBeforeAll, when } from 'test-fns';

import { check, fix } from './package-lock.json.declapract';

/**
 * .what = the forget-not-destroy clamp for the package-lock.json bad-practice.
 * .why  = the fix DELETES the npm lockfile, so it is destructive — `rule.require.clamp-edge-cases`
 *         demands a regression clamp that BITES. the gate reads the real filesystem for a
 *         `pnpm-lock.yaml` beside the lockfile, so this is an integration test (a filesystem
 *         boundary, per `rule.forbid.unit.remote-boundaries`), built on the `mkdtempSync`
 *         throwaway-root pattern from `howto.craft-practice-migrations`. it proves BOTH paths:
 *         delete-when-safe (pnpm-lock.yaml present) and skip-when-unsafe (absent) — the second
 *         guards the forget-not-destroy contract: a bare EXISTS default-delete would fail it.
 */
/**
 * .what = builds the minimal FileCheckContext the check and fix functions actually use
 * .why  = declapract's FileCheckContext carries many fields the package-lock check/fix never
 *         touch — they read only `getProjectRootDirectory()` (to look for a `pnpm-lock.yaml`
 *         beside the lockfile). the single documented cast here is the sanctioned test-context
 *         idiom (howto.craft-practice-migrations); it is confined to this helper so no call
 *         site casts. removal path: drop the cast the day declapract exports a partial-context
 *         builder.
 */
const genContextForRoot = (root: string): FileCheckContext =>
  ({ getProjectRootDirectory: () => root }) as unknown as FileCheckContext;

describe('pnpm package-lock-json — forget-not-destroy gate', () => {
  // .note = deliberate mutation — `roots` accumulates every temp dir genRoot mints so the
  //         afterAll below can remove them all; a scoped, single-threaded test-cleanup zone
  //         (rule.require.immutable-vars sanctions in-place mutation with this note).
  const roots: string[] = [];
  const genRoot = (slug: string, files: Record<string, string>): string => {
    const root = mkdtempSync(path.join(tmpdir(), `pnpm-lock-${slug}-`));
    for (const [name, body] of Object.entries(files))
      writeFileSync(path.join(root, name), body);
    roots.push(root);
    return root;
  };

  afterAll(() => {
    for (const root of roots) rmSync(root, { recursive: true, force: true });
  });

  given('[case1] a package-lock.json WITH a pnpm-lock.yaml beside it', () => {
    const state = useBeforeAll(async () => {
      const root = genRoot('safe', {
        'package-lock.json': '{}',
        'pnpm-lock.yaml': 'lockfileVersion: 9\n',
      });
      const context = genContextForRoot(root);
      return { context, fixed: (await fix('{}', context)).contents };
    });

    when('[t0] the bad-practice is evaluated', () => {
      then('check detects it — safe to remove', () => {
        expect(() => check('{}', state.context)).not.toThrow();
      });

      then('fix removes it — contents become null', () => {
        expect(state.fixed).toBeNull();
      });
    });
  });

  given('[case2] a package-lock.json with NO pnpm-lock.yaml beside it', () => {
    const state = useBeforeAll(async () => {
      const root = genRoot('unsafe', { 'package-lock.json': '{}' });
      const context = genContextForRoot(root);
      return { context, fixed: (await fix('{}', context)).contents };
    });

    when('[t0] the bad-practice is evaluated', () => {
      then('check skips it — forget-not-destroy, no pnpm-lock.yaml yet', () => {
        expect(() => check('{}', state.context)).toThrow(
          'does not match bad practice',
        );
      });

      then('fix is a no-op — the npm lockfile is preserved', () => {
        // a bare EXISTS default-delete would make this null, which this test would catch
        expect(state.fixed).toEqual('{}');
      });
    });
  });

  given('[case3] no package-lock.json at all', () => {
    const state = useBeforeAll(async () => {
      const root = genRoot('absent', { 'pnpm-lock.yaml': 'lockfileVersion: 9\n' });
      return { context: genContextForRoot(root) };
    });

    when('[t0] the bad-practice is evaluated', () => {
      then('check skips it — no npm lockfile to remove', () => {
        expect(() => check(null, state.context)).toThrow(
          'does not match bad practice',
        );
      });
    });
  });
});
