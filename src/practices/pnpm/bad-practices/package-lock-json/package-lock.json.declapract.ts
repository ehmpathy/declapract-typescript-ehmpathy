import type { FileCheckFunction, FileFixFunction } from 'declapract';

import { existsSync } from 'node:fs';
import path from 'node:path';

/**
 * .what = detects a `package-lock.json` (the npm lockfile) that is SAFE to remove — i.e. only
 *         once a `pnpm-lock.yaml` sits beside it.
 * .why  = the npm→pnpm migration must be FORGET-NOT-DESTROY: `package-lock.json` is removed ONLY
 *         after `pnpm-lock.yaml` exists, so a fix interrupted midway never leaves the repo
 *         lockfile-less (the wish's stated safety bar). a bare `FileCheckType.EXISTS` would let
 *         declapract's default fix delete the npm lockfile UNCONDITIONALLY — even on a repo that
 *         has not yet run `pnpm install` — which is exactly the destructive strip this gate
 *         forecloses. so the delete is gated on the pnpm lockfile's presence, read from the
 *         project root via `context.getProjectRootDirectory()`.
 */
const hasPnpmLock = (context: {
  getProjectRootDirectory: () => string;
}): boolean =>
  existsSync(path.join(context.getProjectRootDirectory(), 'pnpm-lock.yaml'));

export const check: FileCheckFunction = (contents, context) => {
  // no package-lock.json → no npm lockfile to remove, skip
  if (contents === null) throw new Error('does not match bad practice');

  // forget-not-destroy: without a pnpm-lock.yaml beside it, removal would leave the repo
  // lockfile-less — so this is NOT yet a safe-to-remove npm lockfile, skip
  if (!hasPnpmLock(context)) throw new Error('does not match bad practice');

  // package-lock.json present AND pnpm-lock.yaml present → safe to remove, detected
  return;
};

export const fix: FileFixFunction = (contents, context) => {
  // gate the delete on the pnpm lockfile's presence (forget-not-destroy) — a fix that ran
  // where the check would not detect leaves the file untouched, never lockfile-less
  if (!hasPnpmLock(context)) return { contents };

  // pnpm-lock.yaml exists → remove the redundant npm lockfile
  return { contents: null };
};
