import { given, then, when } from 'test-fns';

import {
  isAdhocLambdaClient,
  withLambdaClientGenMarker,
} from './withLambdaClientGenMarker';

const adhocClient = `import { askLambdaEndpoint } from 'sdk-aws-lambda';

export const getJob = (event: { jobUuid: string }, context: AskContext) =>
  askLambdaEndpoint({ which: { service: 'svc-jobs', function: 'getJob' }, event }, context);
`;

const generatedClient = `// generated by \`sdk-aws-lambda gen\` — do not edit; re-run to update
import { askLambdaEndpoint } from 'sdk-aws-lambda';

export const getJob = askLambdaEndpoint;
`;

describe('withLambdaClientGenMarker (#532)', () => {
  given('[case1] a hand-written client that wraps askLambdaEndpoint', () => {
    when('[t0] it is marked', () => {
      const after = withLambdaClientGenMarker({
        contents: adhocClient,
        relativeFilePath: 'src/access/sdks/svcJobs.ts',
      });

      then('it is detected before, and not after', () => {
        expect(isAdhocLambdaClient({ contents: adhocClient })).toBe(true);
        expect(isAdhocLambdaClient({ contents: after })).toBe(false);
      });

      then('a review marker on line one names the codegen for this peer', () => {
        expect(after.split('\n')[0]).toContain('@declapract:review');
        expect(after).toContain(
          'npx sdk-aws-lambda gen --for svc-jobs --into src/access/svcs/ --env prep',
        );
        expect(after.endsWith(adhocClient)).toBe(true); // the body is left as found
        expect(after).toMatchSnapshot();
      });

      then('a second pass is a no-op', () => {
        expect(
          withLambdaClientGenMarker({
            contents: after,
            relativeFilePath: 'src/access/sdks/svcJobs.ts',
          }),
        ).toEqual(after);
      });
    });
  });

  given('[case2] a client the codegen emitted', () => {
    then('it is not detected', () => {
      expect(isAdhocLambdaClient({ contents: generatedClient })).toBe(false);
    });
  });

  given('[case3] a file in the client dir that never asks a lambda', () => {
    then('it is not detected', () => {
      expect(
        isAdhocLambdaClient({ contents: "export const svcJobsName = 'svc-jobs';\n" }),
      ).toBe(false);
    });
  });

  given('[case4] a peer name the file name does not spell', () => {
    then('the marker leaves a placeholder for the peer', () => {
      const after = withLambdaClientGenMarker({
        contents: adhocClient,
        relativeFilePath: 'src/data/clients/jobsClient.ts',
      });
      expect(after).toContain('--for <svc-name>');
    });
  });
});
